def _build_minor_arcana() -> tuple[Card, ...]:
    cards = []
    for suit in _SUITS:
        for rank in _RANKS:
            cards.append(
                Card(
                    numeral=f"{suit.name} {rank.numeral}",
                    name=f"{suit.name}{rank.name}",
                    symbol=suit.symbol,
                    upright_keyword=rank.upright_keyword,
                    reversed_keyword=rank.reversed_keyword,
                    upright=(
                        f"在{suit.focus}方面，{rank.upright}；"
                        f"此时的优势是{suit.strength}。"
                    ),
                    reversed=(
                        f"在{suit.focus}方面，{rank.reversed}；"
                        f"需要留意{suit.friction}。"
                    ),
                    action=f"{rank.action}，并核对{suit.reality_check}。",
                    arcana="小阿卡纳",
                    suit=suit.name,
                    rank=rank.name,
                )
            )
    return tuple(cards)


MINOR_ARCANA = _build_minor_arcana()
TAROT_DECK = MAJOR_ARCANA + MINOR_ARCANA
