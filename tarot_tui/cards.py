    symbol: str
    upright_keyword: str
    reversed_keyword: str
    upright: str
    reversed: str
    action: str
    arcana: str = "大阿卡纳"
    suit: str | None = None
    rank: str | None = None

    @property
    def family(self) -> str:
        return self.arcana if self.suit is None else f"{self.arcana} · {self.suit}"


